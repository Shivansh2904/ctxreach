// Builds the GitHub Action's single-file bundle, action/dist/ctxreach.cjs.
//
// The Action runs `node action/dist/ctxreach.cjs` (see action.yml), so the
// bundle is committed: a workflow that uses the Action gets no npm install.
// Everything it needs, zod and smol-toml included, is inlined. The entry is
// a few lines below that call runAction() from src/report/annotations.ts.
//
// The output is deterministic (same sources, same esbuild from the lockfile,
// same bytes on every OS), so a fresh build can be compared with the
// committed file byte for byte:
//
//   node scripts/bundle-action.mjs            write action/dist/ctxreach.cjs
//   node scripts/bundle-action.mjs --check    exit 1 if the committed bundle
//                                             differs from a fresh build
//   node scripts/bundle-action.mjs --check --against <file>
//                                             compare with <file> instead
//
// esbuild is the one tsup uses (resolved through tsup), so the bundle is
// built by the version package-lock.json pins.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const BUNDLE = path.join(ROOT, "action", "dist", "ctxreach.cjs");

const ENTRY = `import { version } from "./package.json";
import { escapeData, runAction } from "./src/report/annotations.ts";

try {
  const result = runAction({
    env: process.env,
    cwd: process.cwd(),
    version,
    stdout: (text) => process.stdout.write(text),
    stderr: (text) => process.stderr.write(text),
  });
  process.exitCode = result.status;
} catch (err) {
  process.stdout.write("::error title=ctxreach::" + escapeData(String((err && err.stack) || err)) + "\\n");
  process.exitCode = 2;
}
`;

const BANNER =
  "// Generated by scripts/bundle-action.mjs from src/ (ctxreach's GitHub Action). Do not edit:\n" +
  "// rebuild with `node scripts/bundle-action.mjs`; CI fails when this file differs from a fresh build.";

/** Build the bundle in memory and return its bytes. */
export async function buildBundle() {
  const require = createRequire(pathToFileURL(path.join(ROOT, "node_modules", "tsup", "package.json")));
  const esbuild = await import(pathToFileURL(require.resolve("esbuild")).href);
  const result = await esbuild.build({
    stdin: { contents: ENTRY, resolveDir: ROOT, sourcefile: "action-entry.ts", loader: "ts" },
    absWorkingDir: ROOT,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    banner: { js: BANNER },
    outfile: BUNDLE,
    write: false,
    logLevel: "silent",
  });
  const file = result.outputFiles.find((f) => path.resolve(f.path) === path.resolve(BUNDLE));
  if (!file) throw new Error(`esbuild did not produce ${BUNDLE}`);
  return Buffer.from(file.contents);
}

/** Index of the first byte where `a` and `b` differ, or -1. */
export function firstDifference(a, b) {
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) if (a[i] !== b[i]) return i;
  return a.length === b.length ? -1 : n;
}

async function main(argv) {
  const check = argv.includes("--check");
  const at = argv.indexOf("--against");
  const against = at >= 0 ? path.resolve(argv[at + 1] ?? "") : BUNDLE;
  const fresh = await buildBundle();
  const shown = path.relative(process.cwd(), against) || against;
  if (!check) {
    mkdirSync(path.dirname(BUNDLE), { recursive: true });
    writeFileSync(BUNDLE, fresh);
    process.stdout.write(`wrote ${path.relative(process.cwd(), BUNDLE)} (${fresh.length} bytes)\n`);
    return 0;
  }
  if (!existsSync(against)) {
    process.stderr.write(`${shown} does not exist; run node scripts/bundle-action.mjs\n`);
    return 1;
  }
  const committed = readFileSync(against);
  const diff = firstDifference(committed, fresh);
  if (diff === -1) {
    process.stdout.write(`${shown} matches a fresh build (${fresh.length} bytes)\n`);
    return 0;
  }
  process.stderr.write(
    `${shown} differs from a fresh build at byte ${diff} (committed ${committed.length} bytes, fresh ${fresh.length}). ` +
      "Run node scripts/bundle-action.mjs and commit action/dist/ctxreach.cjs.\n",
  );
  return 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => (process.exitCode = code),
    (err) => {
      process.stderr.write(`${err.stack ?? err}\n`);
      process.exitCode = 2;
    },
  );
}
